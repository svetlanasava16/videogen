/**
 * Глубина сцены — три плана, как в бумажном театре (South Park): чем дальше, тем выше стопы и мельче фигура.
 *
 *   z = 1    дальний план (back): стопы на линии стены y = 1190, масштаб 0.8 — там, где раньше стояли все куклы;
 *   z = 0.5  средний план (mid, по умолчанию): стопы y ≈ 1275, масштаб 1.0;
 *   z = 0    передний план (front): стопы y ≈ 1360, масштаб 1.2.
 *
 * Координаты — кадр 1080×1920 (фоны рисуются в нём же). Пол в фонах нарисован ниже 1190, поэтому планы не требуют перерисовки.
 * Этим модулем пользуются движок (Joke.tsx: куклы, мебель, машины), фоны (где рисовать сиденья) и документация (docs/ENGINE.md).
 */
import { PLANES, type Plane } from "@jf/core";

/** Линия стены — стопы дальнего плана (= FLOOR_Y фонов в backdrops/parts.tsx). */
export const WALL_Y = 1190;
/** На сколько ниже стоят стопы переднего плана, чем дальнего (px кадра). */
export const DEPTH_Y = 170;
/** Высота бокса куклы среднего плана (px кадра) — 0.4 высоты кадра. */
export const PUPPET_BOX_H = 768;
/** Высота сиденья над полом (px кадра при масштабе 1): верх стула, скамьи, сиденья машины под сидящую куклу. */
export const SEAT_H = 72;

const k = (height: number) => height / 1920;

/** y стоп на плане z (px кадра высотой height). */
export const feetY = (z: number, height = 1920) => (WALL_Y + (1 - z) * DEPTH_Y) * k(height);
/** Масштаб фигуры на плане z (1 — средний план). */
export const depthScale = (z: number) => 0.8 + 0.4 * (1 - z);
/** y верха сиденья на плане z: здесь рисуется сиденье стула/скамьи, чтобы кукла села ровно на него. */
export const seatTopY = (z: number, height = 1920) => feetY(z, height) - SEAT_H * depthScale(z) * k(height);
/** План по имени → z. */
export const zOfPlane = (p: Plane | undefined, fallback: number = PLANES.mid) => (p ? PLANES[p] : fallback);
/** Насколько дорожка прохода отходит от плана (обход впереди или за спинами). */
export const LANE = 0.38;
